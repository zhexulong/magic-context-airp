// GameBuddy embedded-surface boundary check.
//
// Asserts that the vendored Magic Context Pi extension still contains the
// GameBuddy-specific embedded-runtime boundaries. Fragments are compared with
// whitespace collapsed so a reformat (line wrap, indentation change) cannot
// silently disable this gate — an assertion that can never match is worse than
// no assertion, because it reads as coverage.
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const sourceRoot = resolve(import.meta.dirname, "..", "src");
const indexSource = await readFile(resolve(sourceRoot, "index.ts"), "utf8");
const collapse = (value) => value.replace(/\s+/g, " ");
const normalizedSource = collapse(indexSource);

const required = [
  // CLI authoring runners are disabled whenever the runtime is embedded.
  "const cliAuthoringDisabled = embeddedRuntime || embeddedRuntimeDisablesCliAuthoringCommands()",
  "const recompRunner = cliAuthoringDisabled",
  "const wrapupRunner = cliAuthoringDisabled",
  // An embedded runtime selects the SDK-backed runner, never a CLI spawner.
  "embeddedRuntime ? new EmbeddedPiHistorianRunner() : undefined",
  // The Host-facing private seam that binds the embedded ModelRegistry.
  "getEmbeddedHistorianRuntimeBinding",
];
for (const fragment of required) {
  if (!normalizedSource.includes(collapse(fragment))) {
    throw new Error(`missing GameBuddy embedded boundary: ${fragment}`);
  }
}

// The ongoing-interaction historian prompt is GENERATED from its Markdown source by
// `packages/plugin/scripts/build-ongoing-interaction-historian-prompt.ts`, and nothing ran that
// generator automatically - so editing the source and forgetting to regenerate shipped the OLD prompt
// while the diff said otherwise. That is the failure this file exists to prevent, so it is checked
// here with a full-text comparison: a change to the generator's own template must fail here too rather
// than pass unnoticed.
const promptSource = (
  await readFile(
    resolve(sourceRoot, "..", "..", "plugin", "src", "hooks", "magic-context", "ongoing-interaction-historian-prompt.source.md"),
    "utf8",
  )
).trimEnd();
const escapedPrompt = promptSource.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const expectedGenerated =
  `// AUTO-GENERATED by scripts/build-ongoing-interaction-historian-prompt.ts\n// DO NOT EDIT BY HAND.\n\n` +
  `export const ONGOING_INTERACTION_HISTORIAN_SYSTEM_PROMPT = \`${escapedPrompt}\`;\n`;
const generatedPrompt = await readFile(
  resolve(sourceRoot, "..", "..", "plugin", "src", "hooks", "magic-context", "ongoing-interaction-historian-prompt.generated.ts"),
  "utf8",
);
if (generatedPrompt !== expectedGenerated) {
  throw new Error(
    "stale ongoing-interaction historian prompt: regenerate it with " +
      "`bun run packages/plugin/scripts/build-ongoing-interaction-historian-prompt.ts`",
  );
}

console.log(JSON.stringify({
  state: "passed",
  cliBackedAdminRunners: "disabled-in-embedded-mode",
  historianRunner: "embedded-sdk-only",
  externalPiCli: "forbidden-in-embedded-mode",
  ongoingInteractionPrompt: "generated-from-source",
}));