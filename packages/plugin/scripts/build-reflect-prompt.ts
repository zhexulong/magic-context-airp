#!/usr/bin/env bun
/** Generates the bundled reflection (dreamer `reflect`) system prompt from its Markdown source. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../src/hooks/magic-context/reflect-prompt.source.md");
const output = resolve(here, "../src/hooks/magic-context/reflect-prompt.generated.ts");
const raw = readFileSync(source, "utf8").trimEnd();

for (const marker of [
  "# Reflection — Companion Self/Other Memory",
  "<learnings>",
  'Write "I" for yourself and "you" for the player',
  "model inference",
  "An empty answer is a valid answer",
]) {
  if (!raw.includes(marker)) throw new Error(`reflect prompt missing required marker ${marker}`);
}

const escaped = raw.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
writeFileSync(
  output,
  `// AUTO-GENERATED by scripts/build-reflect-prompt.ts from reflect-prompt.source.md\n// DO NOT EDIT BY HAND. Regenerate: bun run packages/plugin/scripts/build-reflect-prompt.ts\n\nexport const REFLECT_SYSTEM_PROMPT = \`${escaped}\`;\n`,
  "utf8",
);
console.log(`build-reflect-prompt: emitted ${raw.length} chars → ${output}`);
